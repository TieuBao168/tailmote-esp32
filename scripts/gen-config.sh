# Read secrets/secrets.env (the form) and generate:
#   secrets/{esp32,linux}.key/.pub, secrets/psk  WireGuard keys (kept across runs)
#   secrets/wg-esp.conf                          Linux peer config for wg-quick
#   <fw>/sdkconfig.secrets                       firmware Kconfig values
. "$(dirname "$0")/common.sh"
load_secrets
command -v wg >/dev/null || die "thiếu wireguard-tools: sudo apt install wireguard-tools"

# ---- validate the form ----
errors=0
err() { bad "$*"; errors=$((errors + 1)); }
is_ip() { [[ "$1" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]]; }
is_key() { [[ "$1" =~ ^[A-Za-z0-9+/]{42}[AEIMQUYcgkosw048]=$ ]]; }

info "kiểm tra $SECRETS_FILE"
[[ -n "${WIFI_SSID:-}" ]] || err "WIFI_SSID trống"
(( ${#WIFI_SSID} <= 32 )) || err "WIFI_SSID dài hơn 32 byte"
if [[ -n "${WIFI_PASSWORD:-}" ]] && (( ${#WIFI_PASSWORD} < 8 || ${#WIFI_PASSWORD} > 63 )); then
  err "WIFI_PASSWORD phải 8–63 ký tự (hoặc để trống cho mạng mở)"
fi
for v in LINUX_TUNNEL_IP ESP_TUNNEL_IP TUNNEL_NETMASK; do
  is_ip "${!v}" || err "$v không phải IPv4: '${!v}'"
done
[[ "$LINUX_TUNNEL_IP" != "$ESP_TUNNEL_IP" ]] || err "LINUX_TUNNEL_IP trùng ESP_TUNNEL_IP"
[[ "$WG_PORT" =~ ^[0-9]+$ ]] && (( WG_PORT > 0 && WG_PORT < 65536 )) || err "WG_PORT không hợp lệ"
[[ "$WG_KEEPALIVE" =~ ^[0-9]+$ ]] || err "WG_KEEPALIVE phải là số giây"
[[ "$WIFI_POWER_SAVE" == none || "$WIFI_POWER_SAVE" == min_modem ]] || err "WIFI_POWER_SAVE: none | min_modem"
for v in ESP_PRIVATE_KEY LINUX_PRIVATE_KEY; do
  [[ -z "${!v:-}" ]] || is_key "${!v}" || err "$v không phải khóa WireGuard base64"
done
[[ -z "${PRESHARED_KEY:-}" || "$PRESHARED_KEY" == auto ]] || is_key "$PRESHARED_KEY" || err "PRESHARED_KEY không hợp lệ"

if [[ -z "${WG_ENDPOINT:-}" ]]; then
  WG_ENDPOINT="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')"
  [[ -n "$WG_ENDPOINT" ]] && ok "WG_ENDPOINT tự động: $WG_ENDPOINT" || err "không tự lấy được IP LAN, điền WG_ENDPOINT"
fi
(( errors == 0 )) || die "form có $errors lỗi — sửa $SECRETS_FILE rồi chạy lại"
ok "form hợp lệ"

# ---- keys ----
umask 077
key_for() { # name, value-from-form
  local name="$1" val="$2"
  if [[ -n "$val" ]]; then
    printf '%s\n' "$val" > "$SECRETS_DIR/$name.key"
  elif [[ ! -f "$SECRETS_DIR/$name.key" ]]; then
    wg genkey > "$SECRETS_DIR/$name.key"
    ok "sinh khóa mới: $name"
  fi
  wg pubkey < "$SECRETS_DIR/$name.key" > "$SECRETS_DIR/$name.pub"
}
key_for esp32 "${ESP_PRIVATE_KEY:-}"
key_for linux "${LINUX_PRIVATE_KEY:-}"

PSK=""
if [[ "${PRESHARED_KEY:-}" == auto ]]; then
  [[ -f "$SECRETS_DIR/psk" ]] || wg genpsk > "$SECRETS_DIR/psk"
  PSK="$(cat "$SECRETS_DIR/psk")"
elif [[ -n "${PRESHARED_KEY:-}" ]]; then
  PSK="$PRESHARED_KEY"
fi

# ---- Linux peer ----
{
  echo "# Generated by scripts/gen-config.sh — do not commit."
  echo "# sudo wg-quick up $SECRETS_DIR/wg-esp.conf"
  echo "[Interface]"
  echo "Address = $LINUX_TUNNEL_IP/$TUNNEL_PREFIX"
  echo "ListenPort = $WG_PORT"
  echo "PrivateKey = $(cat "$SECRETS_DIR/linux.key")"
  echo
  echo "[Peer]"
  echo "# ESP32 DOIT DevKit V1"
  echo "PublicKey = $(cat "$SECRETS_DIR/esp32.pub")"
  [[ -n "$PSK" ]] && echo "PresharedKey = $PSK"
  echo "AllowedIPs = $ESP_TUNNEL_IP/32"
} > "$SECRETS_DIR/wg-esp.conf"
ok "Linux peer: $SECRETS_DIR/wg-esp.conf"

# ---- firmware ----
esc() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
{
  echo "# Generated by scripts/gen-config.sh from secrets/secrets.env — do not commit."
  echo "CONFIG_POC_WIFI_SSID=\"$(esc "$WIFI_SSID")\""
  echo "CONFIG_POC_WIFI_PASSWORD=\"$(esc "${WIFI_PASSWORD:-}")\""
  if [[ "$WIFI_POWER_SAVE" == min_modem ]]; then
    echo "CONFIG_POC_WIFI_PS_MIN_MODEM=y"
  else
    echo "CONFIG_POC_WIFI_PS_NONE=y"
  fi
  echo "CONFIG_POC_WG_PRIVATE_KEY=\"$(cat "$SECRETS_DIR/esp32.key")\""
  echo "CONFIG_POC_WG_PEER_PUBLIC_KEY=\"$(cat "$SECRETS_DIR/linux.pub")\""
  echo "CONFIG_POC_WG_PRESHARED_KEY=\"$PSK\""
  echo "CONFIG_POC_WG_PEER_ENDPOINT=\"$(esc "$WG_ENDPOINT")\""
  echo "CONFIG_POC_WG_PEER_PORT=$WG_PORT"
  echo "CONFIG_POC_WG_LOCAL_IP=\"$ESP_TUNNEL_IP\""
  echo "CONFIG_POC_WG_LOCAL_NETMASK=\"$TUNNEL_NETMASK\""
  echo "CONFIG_POC_WG_KEEPALIVE=$WG_KEEPALIVE"
} > "$FW_DIR/sdkconfig.secrets"
chmod 600 "$FW_DIR/sdkconfig.secrets"
ok "firmware: $FW_DIR/sdkconfig.secrets"

cat <<EOF

  Linux  $LINUX_TUNNEL_IP  ←UDP $WG_ENDPOINT:$WG_PORT→  ESP32 $ESP_TUNNEL_IP
  Tiếp theo:  make build   (và  make peer-up  khi có board)
EOF
